#!/usr/bin/env python3
"""Bundle the product CSV tables into tables.js so the matrix can show them when index.html is
opened straight from disk (file://), where browsers block fetch() of local files.

Usage:  python3 build_tables_js.py <index_dir> <table_dir> [<table_dir> ...]

<table_dir> paths are relative to <index_dir> (the folder holding index.html). Every *.csv under
them is stored in window.CINDRA_TABLES, keyed by its path relative to index.html exactly as
products.js resolves it (e.g. '../outputs/tables/<station>/T_mean_summary_table_<station>.csv').

  python3 build_tables_js.py . figures ../outputs/tables ../notebooks/matrix_cc/figures   # CIndRA
  python3 build_tables_js.py . figures outputs/tables outputs/mhw                       # CIndRA_web
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path


def main(index_dir: str, table_dirs: list[str]) -> None:
    index_dir = Path(index_dir).resolve()
    tables = {}
    for rel in table_dirs:
        root = (index_dir / rel).resolve()
        if not root.is_dir():
            print(f"Warning: {root} not found, skipped", file=sys.stderr)
            continue
        for csv in sorted(root.rglob("*.csv")):
            key = Path(os.path.relpath(csv, index_dir)).as_posix()
            tables[key] = csv.read_text(encoding="utf-8", errors="replace")
    out = index_dir / "tables.js"
    out.write_text(
        "// Generated by build_tables_js.py -- product CSV tables bundled for file:// viewing. Do not edit.\n"
        "window.CINDRA_TABLES = " + json.dumps(tables, ensure_ascii=False, indent=0) + ";\n",
        encoding="utf-8",
    )
    print(f"Bundled {len(tables)} tables ({out.stat().st_size / 1024:.0f} KB) into {out}")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2:])
