"""Convert data/regional/Pacific_EEZs shapefile into matrix_cc/eez.js for the product matrix map.

Dependency-free (reads .shp/.dbf with struct). Longitudes are shifted to 0-360 so the
Pacific is continuous across the dateline, and rings are simplified (Douglas-Peucker).

Usage (from the repository root):  python matrix_cc/build_eez.py
"""
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'data' / 'regional' / 'Pacific_EEZs' / 'Pacific_EEZs'
OUT = Path(__file__).resolve().parent / 'eez.js'
TOLERANCE = 0.03  # degrees


def read_dbf(path):
    d = path.with_suffix('.dbf').read_bytes()
    n, header_len, rec_len = struct.unpack('<IHH', d[4:12])
    fields, i = [], 32
    while d[i] != 0x0D:
        fields.append((d[i:i + 11].split(b'\0')[0].decode(), d[i + 16]))
        i += 32
    rows = []
    for r in range(n):
        rec, o, row = d[header_len + r * rec_len + 1: header_len + (r + 1) * rec_len], 0, {}
        for name, length in fields:
            row[name] = rec[o:o + length].decode('latin1').strip()
            o += length
        rows.append(row)
    return rows


def read_polygons(path):
    d = path.with_suffix('.shp').read_bytes()
    pos, shapes = 100, []
    while pos < len(d):
        content_len = struct.unpack('>i', d[pos + 4:pos + 8])[0] * 2
        rec = d[pos + 8: pos + 8 + content_len]
        pos += 8 + content_len
        if struct.unpack('<i', rec[:4])[0] != 5:
            shapes.append([])
            continue
        n_parts, n_points = struct.unpack('<2i', rec[36:44])
        parts = list(struct.unpack(f'<{n_parts}i', rec[44:44 + 4 * n_parts])) + [n_points]
        base = 44 + 4 * n_parts
        pts = [struct.unpack('<2d', rec[base + 16 * k: base + 16 * (k + 1)]) for k in range(n_points)]
        shapes.append([pts[parts[k]:parts[k + 1]] for k in range(n_parts)])
    return shapes


def simplify_ring(ring, tol):
    """Closed rings start and end on the same point, so simplify each half separately."""
    mid = len(ring) // 2
    return simplify(ring[:mid + 1], tol)[:-1] + simplify(ring[mid:], tol)


def simplify(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        norm = (dx * dx + dy * dy) ** 0.5 or 1e-12
        best, idx = 0.0, None
        for k in range(a + 1, b):
            dist = abs(dy * pts[k][0] - dx * pts[k][1] + x2 * y1 - y2 * x1) / norm
            if dist > best:
                best, idx = dist, k
        if idx is not None and best > tol:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]


def main():
    features = []
    for row, rings in zip(read_dbf(SRC), read_polygons(SRC)):
        polys = []  # shapefile: clockwise rings are outer boundaries, counter-clockwise rings are holes
        for ring in rings:
            ring = [(x + 360 if x < 0 else x, y) for x, y in ring]
            area = sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:]))
            ring = simplify_ring(ring, TOLERANCE)
            if len(ring) < 4:
                continue
            coords = [[round(x, 3), round(y, 3)] for x, y in ring]
            if area <= 0 or not polys:
                polys.append([coords])
            else:
                polys[-1].append(coords)
        if polys:
            features.append({
                'type': 'Feature',
                'properties': {'name': row['Country'], 'sovereign': row['Sovereign'], 'iso': row['ISO_3digit']},
                'geometry': {'type': 'MultiPolygon', 'coordinates': polys},
            })
    geo = {'type': 'FeatureCollection', 'features': features}
    OUT.write_text('// Generated by build_eez.py from data/regional/Pacific_EEZs. Do not edit.\n'
                   'window.CINDRA_EEZ = ' + json.dumps(geo, separators=(',', ':')) + ';\n')
    print(f'{len(features)} EEZs -> {OUT} ({OUT.stat().st_size / 1024:.0f} KB)')


if __name__ == '__main__':
    main()
